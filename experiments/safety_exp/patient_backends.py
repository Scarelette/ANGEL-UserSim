"""Simulated-patient backends for the red-team transcript generator.

In the red-team replay the *user* side of the conversation (the person talking
to a chatbot) is played by the Angel patient simulator, and the *assistant*
side is generated by Claude. Two ways to reach the patient simulator:

``http``   (used for the paper's runs)
    A Claude-Messages-style HTTP service in front of the Angel Actor:
    ``POST {base_url}/session/init`` and ``POST {base_url}/v1/messages`` with
    ``{model, messages, username, session_id, profile_id}``; the response has
    Anthropic's ``{"content": [{"type": "text", "text": ...}]}`` shape. The
    service keeps per-session state keyed by ``username``/``session_id``.

``angel``  (in-process, no server)
    Loads the Angel model from ``model_usage.angel`` in this process. The
    Actor keeps its own conversation history, so only the latest message is
    passed on each turn, which gives the same conversation as the stateful
    HTTP service.

Both expose ``client.messages.create(model=..., messages=..., max_tokens=...)``
returning the Anthropic response shape, so the generator does not care which
one it talks to.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional


# --------------------------------------------------------------------------- #
# HTTP backend (ported from the study app's AnthropicLocalClient)
# --------------------------------------------------------------------------- #
@dataclass
class _ClientConfig:
    base_url: str
    username: str
    session_id: str
    profile_id: Optional[str]
    timeout: float


class _HTTPMessagesAPI:
    def __init__(self, client: "HTTPPatientClient") -> None:
        self._client = client

    def create(
        self,
        *,
        model: str,
        messages: List[Dict[str, Any]],
        username: Optional[str] = None,
        session_id: Optional[str] = None,
        profile_id: Optional[str] = None,
        conversation_id: Optional[str] = None,
        stream: bool = False,
        timeout: Optional[float] = None,
        **_: Any,
    ) -> Dict[str, Any]:
        """Claude-style call; extra SDK kwargs (max_tokens, ...) are ignored."""
        import requests

        cfg = self._client._cfg
        payload: Dict[str, Any] = {
            "model": model,
            "messages": messages,
            "username": username or cfg.username,
            "session_id": session_id or cfg.session_id,
            "stream": stream,
        }
        if profile_id is not None:
            payload["profile_id"] = profile_id
        elif cfg.profile_id is not None:
            payload["profile_id"] = cfg.profile_id
        if conversation_id is not None:
            payload["conversation_id"] = conversation_id

        resp = requests.post(f"{cfg.base_url}/v1/messages", json=payload, timeout=timeout or cfg.timeout)
        resp.raise_for_status()
        return resp.json()


class HTTPPatientClient:
    """Lightweight Claude-style client for a patient-simulation HTTP service."""

    def __init__(
        self,
        *,
        base_url: str = "http://127.0.0.1:8080",
        username: str = "api_user",
        session_id: str = "default",
        profile_id: Optional[str] = None,
        timeout: float = 300.0,
    ) -> None:
        self._cfg = _ClientConfig(
            base_url=base_url.rstrip("/"),
            username=username,
            session_id=session_id,
            profile_id=profile_id,
            timeout=timeout,
        )
        self.messages = _HTTPMessagesAPI(self)

    def init_session(self) -> Dict[str, Any]:
        import requests

        payload: Dict[str, Any] = {"username": self._cfg.username, "session_id": self._cfg.session_id}
        if self._cfg.profile_id is not None:
            payload["profile_id"] = self._cfg.profile_id
        resp = requests.post(f"{self._cfg.base_url}/session/init", json=payload, timeout=self._cfg.timeout)
        resp.raise_for_status()
        return resp.json()


# --------------------------------------------------------------------------- #
# In-process Angel backend
# --------------------------------------------------------------------------- #
class _AngelMessagesAPI:
    def __init__(self, client: "InProcessAngelClient") -> None:
        self._client = client

    def create(self, *, messages: List[Dict[str, Any]], **_: Any) -> Dict[str, Any]:
        c = self._client
        latest = next(
            (m["content"] for m in reversed(messages) if m.get("role") == "user" and m.get("content")),
            "",
        )
        # Pass the profile only on the first turn. Passing it again would make the
        # Observer re-expand it every turn (with --patient-expand) and restart the
        # conversation whenever the new expansion differs.
        profile_kwargs = {} if c.started else {"profile_id": c.profile_id, "expand": c.expand}
        result = c.model.send(c.username, latest, session_id=c.session_id, **profile_kwargs)
        c.started = True
        return {"content": [{"type": "text", "text": result["reply"]}]}


class InProcessAngelClient:
    """Drive ``model_usage.angel.AngelModel`` with the HTTP client's interface."""

    def __init__(
        self,
        *,
        profile_id: str,
        username: str = "redteam_replay",
        session_id: str = "default",
        profiles_jsonl: Optional[str] = None,
        backend: Optional[str] = None,
        expand: bool = False,
    ) -> None:
        from model_usage.angel import AngelModel, RunnerConfig

        config = RunnerConfig()
        if profiles_jsonl:
            config.jsonl_path = Path(profiles_jsonl)
        if backend:
            config.backend = backend
        self.model = AngelModel(config)
        self.profile_id = profile_id
        self.username = username
        self.session_id = session_id
        self.expand = expand
        self.started = False
        self.messages = _AngelMessagesAPI(self)

    def init_session(self) -> Dict[str, Any]:
        # Sessions are created lazily on the first send(); validate the id now.
        return {"profile_id": self.model.resolve_profile_id(self.profile_id)}
